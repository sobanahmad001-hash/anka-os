const clean = value => typeof value === 'string' ? value.trim() : ''
const array = value => Array.isArray(value) ? value : []

export function initialDesignAssetComparisonState(contextKey = '') {
  return { contextKey: clean(contextKey), leftAssetId: '', rightAssetId: '' }
}

export function designAssetComparisonReducer(state, action) {
  if (action.type === 'context_changed') {
    const contextKey = clean(action.contextKey)
    return contextKey === state.contextKey ? state : initialDesignAssetComparisonState(contextKey)
  }
  if (action.type === 'clear_all') return initialDesignAssetComparisonState(state.contextKey)
  if (action.type === 'clear_slot' && ['left', 'right'].includes(action.slot)) {
    return { ...state, [action.slot === 'left' ? 'leftAssetId' : 'rightAssetId']: '' }
  }
  if (action.type === 'select_slot' && ['left', 'right'].includes(action.slot)) {
    const assetId = clean(action.assetId)
    const selectedKey = action.slot === 'left' ? 'leftAssetId' : 'rightAssetId'
    const otherKey = action.slot === 'left' ? 'rightAssetId' : 'leftAssetId'
    return { ...state, [selectedKey]: assetId, ...(assetId && assetId === state[otherKey] ? { [otherKey]: '' } : {}) }
  }
  return state
}

function sourceLabel(row) {
  if (row?.sourceType === 'generated') return 'Durable generated output'
  if (row?.sourceType === 'variant') return row.recordedVariantFormat ? `Recorded variant · ${row.recordedVariantFormat.replaceAll('_', ' ')}` : 'Recorded variant'
  return row?.sourceType ? 'Other recorded output' : null
}

function sourceVersion(row) {
  if (!row?.directionVersionId) return null
  return row.directionVersionNumber
    ? `v${row.directionVersionNumber} · ${row.directionVersionId}`
    : row.directionVersionId
}

function modelLabel(row) {
  if (!row?.modelId) return null
  return row.modelName ? `${row.modelName} · ${row.modelId}` : row.modelId
}

const FACTS = Object.freeze([
  ['asset', 'Asset ID', row => clean(row?.id) || null],
  ['status', 'Status', row => clean(row?.status) || null],
  ['mediaType', 'Media type', row => clean(row?.mediaType) || null],
  ['source', 'Recorded source', sourceLabel],
  ['job', 'Generation job', row => clean(row?.jobId) || null],
  ['jobStatus', 'Job status', row => clean(row?.jobStatus) || null],
  ['model', 'Model', modelLabel],
  ['provider', 'Provider', row => clean(row?.provider) || null],
  ['generatedBy', 'Generated by', row => clean(row?.generatedBy) || null],
  ['sourceVersion', 'Recorded direction source', sourceVersion],
  ['created', 'Created timestamp', row => clean(row?.createdAt) || null],
  ['prompt', 'Recorded prompt', row => clean(row?.prompt) || null],
  ['dimensions', 'Dimensions', row => clean(row?.recorded?.dimensions) || null],
  ['mimeType', 'MIME / file format', row => clean(row?.recorded?.mimeType) || null],
  ['name', 'Asset name', row => clean(row?.recorded?.name) || null],
  ['reviewState', 'Review state', row => clean(row?.recorded?.reviewState) || null],
  ['independentVersion', 'Independent asset version', row => clean(row?.recorded?.independentVersion) || null],
])

export function designAssetComparisonModel(rows, state) {
  const assets = array(rows)
  const left = assets.find(row => row.id === clean(state?.leftAssetId)) || null
  const right = assets.find(row => row.id === clean(state?.rightAssetId)) || null
  const ready = Boolean(left && right && left.id !== right.id)
  const facts = ready ? FACTS.map(([key, label, read]) => {
    const leftValue = read(left)
    const rightValue = read(right)
    return {
      key,
      label,
      leftValue,
      rightValue,
      relationship: leftValue === null || rightValue === null ? 'unknown' : leftValue === rightValue ? 'same' : 'different',
    }
  }) : []
  return { left, right, ready, facts }
}

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'

const migration = readFileSync(new URL('../../supabase/migrations/20260825080000_canonical_activity_notifications.sql', import.meta.url), 'utf8')
const hook = readFileSync(new URL('../hooks/useNotifications.js', import.meta.url), 'utf8')

test('notification access is recipient-only and browser inserts are revoked', () => {
  assert.match(migration, /Recipients can read own notifications/)
  assert.match(migration, /\(select auth\.uid\(\)\) = user_id/)
  assert.match(migration, /revoke all on public\.notifications from anon, authenticated/)
  assert.match(migration, /grant select, update on public\.notifications to authenticated/)
  assert.doesNotMatch(hook, /\.insert\(/)
})

test('activity is database-generated by an authorization-checking private trigger', () => {
  assert.match(migration, /function private\.capture_delivery_activity/)
  assert.match(migration, /security definer/)
  assert.match(migration, /set search_path = ''/)
  assert.match(migration, /Actor is not authorized for delivery activity capture/)
  assert.match(migration, /revoke insert on public\.activity_events from authenticated/)
})

test('canonical delivery mutations update the living record and targeted notifications', () => {
  for (const table of ['projects', 'tasks', 'requests', 'deliverable_versions', 'comments']) {
    assert.match(migration, new RegExp(`on public\\.${table}`))
  }
  assert.match(migration, /update public\.living_project_documents/)
  assert.match(migration, /source_version = source_version \+ 1/)
  assert.match(migration, /insert into public\.notifications/)
})

test('notification hook subscribes to each user canonical feed', () => {
  assert.match(hook, /table: 'notifications'/)
  assert.match(hook, /filter: `user_id=eq\.\$\{user\.id\}`/)
  assert.doesNotMatch(hook, /as_notifications/)
  assert.match(hook, /read_at: readAt/)
})

const mapping = new Map(SERVICE_BUSINESS_GROUP_MAPPINGS.map(row => [row.service_id, row.groups]))

export function serviceBusinessCatalogue(snapshot) {
  if (!snapshot || !Array.isArray(snapshot.leaves)) throw Error('Current project service catalogue required')
  const seen = new Set()
  const groups = SERVICE_BUSINESS_GROUPS.map(group => ({...group, services:[]}))
  const unmapped = []
  for (const leaf of snapshot.leaves) {
    if (!leaf || typeof leaf.id !== 'string' || seen.has(leaf.id)) throw Error('Distinct canonical service IDs required')
    seen.add(leaf.id)
    const expected = mapping.get(leaf.id)
    // New/custom entries stay visible as unmapped until explicitly reviewed. No label/department guessing.
    if (!expected) { unmapped.push(leaf); continue }
    if ((leaf.business_group_version !== undefined || leaf.business_groups !== undefined) && (leaf.business_group_version !== SERVICE_BUSINESS_GROUP_VERSION || !Array.isArray(leaf.business_groups) || JSON.stringify(leaf.business_groups) !== JSON.stringify(expected))) {
      throw Error('Service business-group mapping changed; refresh the reviewed catalogue')
    }
    for (const group of groups) if (expected.includes(group.id)) group.services.push(leaf)
  }
  return {version:SERVICE_BUSINESS_GROUP_VERSION, groups, unmapped}
}

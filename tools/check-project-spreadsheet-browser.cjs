// Execute only in the coordinator's permitted local browser runtime.
const assert=require('node:assert/strict'),fs=require('node:fs/promises'),path=require('node:path')
const {chromium}=require(process.argv[2]||'playwright')
const output=process.argv[3]
assert(output,'Evidence directory required')
;(async()=>{
 await fs.mkdir(output,{recursive:true})
 const {syntheticImportWorkbook}=await import('./project-spreadsheet-synthetic-fixture.js')
 const browser=await chromium.launch({headless:process.env.IMPORTER_HEADFUL!=='1'})
 try {
  const results=[]
  for(const width of [1440,390]) {
   const context=await browser.newContext({viewport:{width,height:900}}),page=await context.newPage()
   const errors=[],remote=[];page.on('pageerror',e=>errors.push(e.message))
   await page.route('**/*',route=>{const u=new URL(route.request().url());if(u.hostname==='127.0.0.1'&&u.port==='5178')return route.continue();remote.push(u.origin);return route.abort()})
   await page.goto('http://127.0.0.1:5178/tools/check-project-spreadsheet-browser.html')
   await page.waitForFunction(()=>document.querySelector('#result').textContent.startsWith('PASS'))
   assert.equal((await page.locator('#result').textContent()).split('\n').filter(x=>x.startsWith('PASS')).length,6)
   assert(!(await page.locator('#result').textContent()).includes('FAIL'))
   await page.getByLabel('Source spreadsheet',{exact:true}).setInputFiles({name:'synthetic-pages.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(syntheticImportWorkbook())})
   await page.getByLabel('Import sheet',{exact:true}).waitFor()
   assert.equal(await page.getByLabel('Import sheet',{exact:true}).locator('option:disabled').count(),1)
   await page.getByRole('button',{name:'Preview mapped rows',exact:true}).click()
   await page.getByRole('region',{name:'Spreadsheet row preview'}).waitFor()
   assert((await page.getByRole('region',{name:'Spreadsheet row preview'}).textContent()).includes('synthetic:one'))
   assert.equal(await page.getByRole('alert').count(),0)
   const panel=page.getByRole('dialog',{name:'Project spreadsheet import'});assert(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth),'Importer content must fit its own scrolling viewport')
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Styled synthetic inspector must stay within viewport')
   assert.equal(await page.getByRole('button',{name:/confirm|upload/i}).count(),0)
   assert.deepEqual(remote,[]);assert.deepEqual(errors,[])
   const screenshot=`importer-xlsx-${width}.png`;await page.screenshot({path:path.join(output,screenshot),fullPage:true})
   results.push({width,xmlChecks:6,actualFileInput:true,workerInspection:true,hiddenSheetExcluded:true,rowPreview:true,uploadAndConfirmAbsent:true,remoteRequests:remote,pageErrors:errors,screenshot})
   await page.goto('http://127.0.0.1:5178/tools/check-project-spreadsheet-browser.html?integrated=1')
   await page.getByLabel('Source spreadsheet',{exact:true}).setInputFiles({name:'synthetic-pages.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(syntheticImportWorkbook())})
   await page.getByLabel('Import sheet',{exact:true}).waitFor()
   await page.getByRole('button',{name:'Load current project workstreams',exact:true}).click()
   await page.getByLabel('Import workstream',{exact:true}).selectOption({label:'Synthetic website workstream · active'})
   await page.getByLabel('Draft title',{exact:true}).fill('Synthetic imported draft')
   await page.getByRole('checkbox',{name:'I confirm uploading this source as a private reference.',exact:true}).check()
   await page.getByRole('button',{name:'Upload reviewed private source',exact:true}).click()
   await page.getByRole('button',{name:'Select first 25 visible rows',exact:true}).click()
   await page.getByRole('button',{name:'Review canonical differences',exact:true}).click()
   await page.getByRole('region',{name:'Reviewed changes'}).waitFor()
   assert((await page.getByRole('region',{name:'Reviewed changes'}).textContent()).includes('Synthetic service'))
   await page.getByRole('button',{name:'Save private reviewed proposal',exact:true}).click()
   await page.getByRole('alert').filter({hasText:'Synthetic lost save response'}).waitFor()
   await page.getByRole('button',{name:'Resume original import',exact:true}).click()
   await page.getByRole('button',{name:'Confirm exactly this saved proposal',exact:true}).click()
   await page.getByRole('region',{name:'Import results'}).waitFor()
   assert((await page.getByRole('region',{name:'Import results'}).textContent()).includes('Unapproved draft saved'))
   assert.equal(await page.getByRole('dialog').locator('pre').count(),0)
   await page.getByRole('button',{name:'Review canonical differences',exact:true}).click()
   await page.getByRole('button',{name:'Save private reviewed proposal',exact:true}).click()
   await page.getByRole('button',{name:'Confirm exactly this saved proposal',exact:true}).waitFor()
   await page.reload() // pending UUID-only resume is visible without source selection
   await page.getByRole('button',{name:'Resume original import',exact:true}).waitFor()
   // The fixture has no durable server. This reload is solely a UI recovery
   // affordance check; return to the original state for complete mock journey.
   await page.getByLabel('Source spreadsheet',{exact:true}).setInputFiles({name:'synthetic-pages.xlsx',mimeType:'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',buffer:Buffer.from(syntheticImportWorkbook())})
   // Reload intentionally loses in-memory mock receipt. No new request may be
   // submitted; recover shows a readable missing-receipt message, no JSON/IDs.
   await page.getByRole('button',{name:'Resume original import',exact:true}).click()
   await page.getByRole('alert').filter({hasText:'No saved receipt was found yet'}).waitFor()
   assert.equal(await page.getByRole('dialog').locator('pre').count(),0)
   assert(await page.getByRole('dialog').evaluate(el=>el.scrollWidth<=el.clientWidth),'Integrated drawer must fit its viewport')
   assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Integrated fixture must fit mobile viewport')
   const integratedScreenshot=`importer-integrated-${width}.png`;await page.screenshot({path:path.join(output,integratedScreenshot),fullPage:true})
   results.push({width,scope:'Offline UI + actual parser only; Storage/save/recovery mocks, not live acceptance',namedSelection:true,readableReview:true,noRawJson:true,readableResults:true,sameTabRecoveryAndConfirm:true,lostReceiptRecoveryAffordance:true,viewportBounded:true,screenshot:integratedScreenshot})
   assert.deepEqual(remote,[]);assert.deepEqual(errors,[])
   await context.close()
  }
  await fs.writeFile(path.join(output,'importer-browser-evidence.json'),JSON.stringify({scope:'Synthetic local browser only; no signed-in, Storage, native or provider acceptance',results},null,2)+'\n')
  console.log('PASS two synthetic XLSX file-input browser journeys')
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1})
